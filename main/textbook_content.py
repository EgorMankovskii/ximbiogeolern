def _slugify(value):
    """Делает короткий ASCII-slug для URL учебника или темы."""

    alphabet = {
        'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'e',
        'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm',
        'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u',
        'ф': 'f', 'х': 'h', 'ц': 'c', 'ч': 'ch', 'ш': 'sh', 'щ': 'sch',
        'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya',
    }
    result = []
    previous_dash = False
    for char in value.lower():
        replacement = alphabet.get(char, char)
        for item in replacement:
            if item.isalnum():
                result.append(item)
                previous_dash = False
            elif not previous_dash:
                result.append('-')
                previous_dash = True
    return ''.join(result).strip('-') or 'topic'


def _prepare_textbooks(textbooks):
    """Добавляет slug-и к учебникам и темам, чтобы для них были отдельные страницы."""

    used_books = set()
    for book in textbooks:
        base_book_slug = _slugify(book['title'])
        book_slug = base_book_slug
        counter = 2
        while book_slug in used_books:
            book_slug = f'{base_book_slug}-{counter}'
            counter += 1
        used_books.add(book_slug)
        book['slug'] = book_slug

        used_topics = set()
        for topic in book['topics']:
            base_topic_slug = _slugify(topic['name'])
            topic_slug = base_topic_slug
            counter = 2
            while topic_slug in used_topics:
                topic_slug = f'{base_topic_slug}-{counter}'
                counter += 1
            used_topics.add(topic_slug)
            topic['slug'] = topic_slug
    return textbooks


TEXTBOOKS = _prepare_textbooks(TEXTBOOKS)
